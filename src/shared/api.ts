import type { HubApi } from "./types.js";

type Invoke = (channel: string, ...args: unknown[]) => Promise<any>;
type Listen = <T>(channel: string, cb: (v: T) => void) => () => void;

/**
 * The renderer's API as channel calls. The desktop window binds it to Electron IPC (preload); the phone binds it to
 * Happy's remote WebSocket. Both reach the same handlers in the main process.
 */
export function makeApi(invoke: Invoke, listen: Listen, extras: { pathForFile(file: File): string }): HubApi {
  return {
  list: () => invoke("hub:list"),
  create: (input) => invoke("hub:create", input),
  send: (id, text, images, files) => invoke("hub:send", id, text, images, files),
  setModel: (id, model) => invoke("hub:setModel", id, model),
  setEffort: (id, effort) => invoke("hub:setEffort", id, effort),
  setCodexSandbox: (id, mode) => invoke("hub:setCodexSandbox", id, mode),
  codexModels: () => invoke("hub:codexModels"),
  cursorModels: () => invoke("hub:cursorModels"),
  setCursorMode: (id, mode) => invoke("hub:setCursorMode", id, mode),
  setTags: (id, tags) => invoke("hub:setTags", id, tags),
  setArchived: (id, archived) => invoke("hub:setArchived", id, archived),
  removeWorktree: (id) => invoke("hub:removeWorktree", id),
  forkSession: (id) => invoke("hub:fork", id),
  listWorktrees: (id) => invoke("hub:listWorktrees", id),
  stopProcess: (id, proc) => invoke("hub:stopProcess", id, proc),
  linkWorktree: (id, path) => invoke("hub:linkWorktree", id, path),
  unlinkWorktree: (id, path) => invoke("hub:unlinkWorktree", id, path),
  moveToGroup: (id, groupId) => invoke("hub:moveToGroup", id, groupId),
  groups: () => invoke("hub:groups"),
  createGroup: (name) => invoke("hub:createGroup", name),
  renameGroup: (id, name) => invoke("hub:renameGroup", id, name),
  deleteGroup: (id) => invoke("hub:deleteGroup", id),
  setGroupCollapsed: (id, c) => invoke("hub:setGroupCollapsed", id, c),
  onGroups: (cb) => listen("hub:groups", cb),
  interrupt: (id) => invoke("hub:interrupt", id),
  remove: (id) => invoke("hub:remove", id),
  rename: (id, title) => invoke("hub:rename", id, title),
  setPermissionMode: (id, mode) => invoke("hub:setPermissionMode", id, mode),
  respondPermission: (requestId, decision, extra) => invoke("hub:respondPermission", requestId, decision, extra),
  pickFolder: () => invoke("hub:pickFolder"),
  pickFile: (cwd) => invoke("hub:pickFile", cwd),
  pickFiles: (cwd) => invoke("hub:pickFiles", cwd),
  listClaudeSessions: () => invoke("hub:listClaudeSessions"),
  claudeModels: () => invoke("claude:models"),
  saveAttachment: (dataUrl) => invoke("hub:saveAttachment", dataUrl),
  pathForFile: (file) => extras.pathForFile(file),
  readFile: (path) => invoke("hub:readFile", path),
  resolveLink: (sessionId, raw) => invoke("hub:resolveLink", sessionId, raw),
  readDir: (path) => invoke("hub:readDir", path),
  listFiles: (root) => invoke("fs:list", root),
  writeFile: (sessionId, path, text) => invoke("fs:write", sessionId, path, text),
  gitDiff: (cwd, path) => invoke("hub:gitDiff", cwd, path),
  gitChanges: (cwd) => invoke("hub:gitChanges", cwd),
  usageToday: () => invoke("hub:usageToday"),
  onUsage: (cb) => listen("hub:usage", cb),
  limits: () => invoke("hub:limits"),
  overview: (refresh) => invoke("hub:overview", refresh),
  onOverview: (cb) => listen("hub:overview", cb),
  onLimits: (cb) => listen("hub:limits", cb),
  revealFile: (path) => invoke("hub:revealFile", path),
  openFile: (path) => invoke("hub:openFile", path),
  browserSetBounds: (id, rect) => invoke("browser:setBounds", id, rect),
  browserNavigate: (id, url) => invoke("browser:navigate", id, url),
  browserNav: (id, action) => invoke("browser:nav", id, action),
  browserState: (id) => invoke("browser:state", id),
  onBrowserState: (cb) => listen("browser:state", cb),
  onBrowserMenu: (cb) => listen("browser:menu", cb),
  browserSnapshot: (id) => invoke("browser:snapshot", id),
  browserEdit: (id, action, x, y) => invoke("browser:edit", id, action, x, y),
  onBrowserActivity: (cb) => listen("browser:activity", cb),
  simplify: (sessionId, itemId) => invoke("hub:simplify", sessionId, itemId),
  gcloudStatus: () => invoke("gcloud:status"),
  cloud: (refresh) => invoke("hub:cloud", refresh),
  analytics: (q) => invoke("hub:analytics", q),
  analyticsEvent: (id, ts) => invoke("hub:analyticsEvent", id, ts),
  onCloud: (cb) => listen("hub:cloud", cb),
  cloudChat: () => invoke("hub:cloudChat"),
  emailChat: () => invoke("hub:emailChat"),
  emailAttachment: (messageId, attachment) => invoke("email:attachment", messageId, attachment),
  emailAsk: (text, threadId) => invoke("hub:emailAsk", text, threadId),
  newSystemChat: (id) => invoke("hub:newSystemChat", id),
  cloudSpawn: (input) => invoke("hub:cloudSpawn", input),
  cloudAsk: (text, board) => invoke("hub:cloudAsk", text, board),
  restartApp: (rebuild) => invoke("app:restart", rebuild),
  codexThreads: () => invoke("import:codexThreads"),
  pinItem: (id, itemId, pinned) => invoke("hub:pin", id, itemId, pinned),
  stats: (refresh, range) => invoke("hub:stats", refresh, range),
  linkPreview: (url) => invoke("link:preview", url),
  routines: () => invoke("routines:list"),
  routineRuns: (id) => invoke("routines:runs", id),
  showRoutineRun: (id, runId) => invoke("routines:show", id, runId),
  projectConfig: () => invoke("hub:projectConfig"),
  openInChrome: (url) => invoke("link:chrome", url),
  codexPrices: () => invoke("prices:get"),
  refreshCodexPrices: () => invoke("prices:refresh"),
  termCreate: (id, cwd, cols, rows, command) => invoke("term:create", id, cwd, cols, rows, command),
  termList: () => invoke("term:list"),
  termRun: (sessionId, command) => invoke("term:run", sessionId, command),
  termIdle: () => invoke("term:idle"),
  deployStarted: (job) => invoke("deploy:started", job),
  deployJobs: () => invoke("deploy:jobs"),
  deployDismiss: (id) => invoke("deploy:dismiss", id),
  onDeployJobs: (cb) => listen("deploy:jobs", cb),
  termWrite: (id, data) => invoke("term:write", id, data),
  termResize: (id, cols, rows) => invoke("term:resize", id, cols, rows),
  termKill: (id) => invoke("term:kill", id),
  onTermData: (cb) => listen("term:data", cb),
  onTermExit: (cb) => listen("term:exit", cb),
  editQueued: (id, qid, text) => invoke("queue:edit", id, qid, text),
  removeQueued: (id, qid) => invoke("queue:remove", id, qid),
  sendQueuedNow: (id, qid) => invoke("queue:sendNow", id, qid),
  addTodo: (id, todo) => invoke("todo:add", id, todo),
  updateTodo: (id, todoId, patch) => invoke("todo:update", id, todoId, patch),
  removeTodo: (id, todoId) => invoke("todo:remove", id, todoId),
  importCodex: (ids) => invoke("import:codex", ids),
  remoteStatus: () => invoke("remote:status"),
  remoteEnable: (on) => invoke("remote:enable", on),
  remoteNewCode: () => invoke("remote:newCode"),
  remoteRemoveDevice: (id) => invoke("remote:removeDevice", id),
  settings: () => invoke("settings:get"),
  saveSettings: (patch) => invoke("settings:save", patch),
  onSettings: (cb) => listen("settings:changed", cb),
  onFocusSession: (cb) => listen("hub:focusSession", cb),
  gmailStatus: () => invoke("gmail:status"),
  calendarEvents: (timeMin, timeMax) => invoke("cal:events", timeMin, timeMax),
  calendarSave: (input, opts) => invoke("cal:save", input, opts),
  calendarDelete: (id, notify) => invoke("cal:delete", id, notify),
  calendarRespond: (id, response) => invoke("cal:respond", id, response),
  calendarParse: (text) => invoke("cal:parse", text),
  onCalendarChanged: (cb) => listen("cal:changed", cb),
  gmailSetClient: (id, secret) => invoke("gmail:setClient", id, secret),
  gmailSignIn: () => invoke("gmail:signIn"),
  gmailSignOut: () => invoke("gmail:signOut"),
  inbox: (refresh) => invoke("email:inbox", refresh),
  inboxPage: (query, page) => invoke("email:inboxPage", query, page),
  onInbox: (cb) => listen("email:inbox", cb),
  emailThread: (id) => invoke("email:thread", id),
  emailStar: (id, on) => invoke("email:star", id, on),
  emailArchive: (ids) => invoke("email:archive", ids),
  emailArchiveAll: (keepStarred) => invoke("email:archiveAll", keepStarred),
  emailSpam: (ids) => invoke("email:spam", ids),
  emailAutoArchive: (from, archiveExisting) => invoke("email:autoArchive", from, archiveExisting),
  emailDraft: (threadId, instruction, to) => invoke("email:draft", threadId, instruction, to),
  emailReplyDefaults: (threadId) => invoke("email:replyDefaults", threadId),
  emailSaveDraft: (threadId, body, rcpt, draftId, subject, from, html) => invoke("email:saveDraft", threadId, body, rcpt, draftId, subject, from, html),
  emailSendAs: () => invoke("email:sendAs"),
  contacts: () => invoke("contacts:list"),
  emailSend: (draftId) => invoke("email:send", draftId),
  emailTriage: () => invoke("email:triage"),
  emailTriageRun: () => invoke("email:triageRun"),
  emailTriagePick: (picked) => invoke("email:triagePick", picked),
  emailTriageClear: () => invoke("email:triageClear"),
  onTriage: (cb) => listen("email:triage", cb),
  onGoogleStatus: (cb) => listen("gmail:status", cb),
  linearStatus: () => invoke("linear:status"),
  linearSetKey: (key) => invoke("linear:setKey", key),
  linearClearKey: () => invoke("linear:clearKey"),
  tasks: (scope, refresh) => invoke("hub:tasks", scope, refresh),
  onTasks: (cb) => listen("hub:tasks", cb),
  taskDetail: (id) => invoke("hub:taskDetail", id),
  startTask: (issueId, engine) => invoke("hub:startTask", issueId, engine),
  linearMeta: () => invoke("linear:meta"),
  linearUpdate: (id, input) => invoke("linear:update", id, input),
  linearCreate: (input) => invoke("linear:create", input),
  linearParse: (text) => invoke("linear:parse", text),
  gcloudLogin: (kind) => invoke("gcloud:login", kind),
  onGcloudLog: (cb) => listen("gcloud:log", cb),
  setBadge: (count) => invoke("app:setBadge", count),
  attention: () => invoke("app:attention"),
  onUpdate: (cb) => listen("hub:update", cb),
  onRemoved: (cb) => listen("hub:removed", cb),
};
}
